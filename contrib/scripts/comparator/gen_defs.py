"""Generate Comparator/Defs/<module path>.lean: a verbatim copy of every module of the library
`Airy1GumbelContrib`, and the umbrella Comparator/Defs.lean importing them all.

  python3 scripts/comparator/gen_defs.py          # from the package directory contrib/

Why whole modules, under the library's own names. The proof closure of the 103 claimed theorems
(scripts/comparator/CopySpans.lean) reaches 2468 of the library's 2838 ranged declarations, in 94
of its 97 modules, so the copy is the library: nothing is dropped, and a tactic that names a lemma
its final term does not keep still finds it. The copies keep every declaration name: the
Challenge and the Solution import the copies and never the library, so no name is declared twice
in their environments, and a prefix namespace would change how the copied source resolves names
(`open MeasureTheory` inside `namespace P` opens `P.MeasureTheory` once the library declares one).

The only edits: each `import Airy1GumbelContrib.X` becomes `import Comparator.Defs.Airy1GumbelContrib.X`
(Mathlib imports are kept), the leading copyright comment is replaced by the same comment plus a
note, and `#print`/`#check`/`#eval` commands are dropped. A constant of a copy therefore differs
from the library's only where Lean puts the module into a name (`_private.<module>.0.N`).
`scripts/comparator/CheckFidelity.lean` checks that every constant of every copy equals the
library's constant of the same name (private names read with the library's module)."""
