import glob
import os
import re

LIB = "Airy1GumbelContrib"
OUT = "Comparator/Defs"
HDR = """/-
Copyright (c) 2026 Le Chen. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Le Chen
-/"""


def copy_module(src):
    mod = src[:-5].replace("/", ".")
    lines = open(src, encoding="utf-8").read().split("\n")
    imports, body_start = [], 0
    for i, l in enumerate(lines):
        m = re.match(r"^import\s+(\S+)\s*$", l)
        if m:
            x = m.group(1)
            imports.append(f"{OUT.replace('/', '.')}.{x}" if x == LIB or x.startswith(LIB + ".") else x)
            body_start = i + 1
    assert imports, src
    body = [l for l in lines[body_start:]
            if not re.match(r"^\s*#(print|check|eval|reduce|guard_msgs|lint|exit)\b", l)]
    while body and not body[-1].strip():
        body.pop()
    out = [HDR] + [f"import {i}" for i in imports] + [
        "",
        "/-!",
        f"Verbatim copy of the library module `{mod}` (generated by `scripts/comparator/gen_defs.py`;",
        "do not edit): only the library imports are redirected to the copies. Part of the trusted",
        "statement of the comparator tier; `scripts/comparator/CheckFidelity.lean` checks that every",
        "constant declared here equals the library's constant of the same name.",
        "-/",
    ] + body + [""]
    dst = f"{OUT}/{src}"
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "w", encoding="utf-8").write("\n".join(out))


def main():
    srcs = sorted(glob.glob(f"{LIB}/**/*.lean", recursive=True))
    for s in srcs:
        copy_module(s)
    umb = [HDR] + [f"import {OUT.replace('/', '.')}.{s[:-5].replace('/', '.')}" for s in srcs] + [
        "",
        "/-! Every copied library module (generated by `scripts/comparator/gen_defs.py`). -/",
        ""]
    open(f"{OUT}.lean", "w", encoding="utf-8").write("\n".join(umb))
    print(len(srcs), "module(s) copied")


if __name__ == "__main__":
    main()
