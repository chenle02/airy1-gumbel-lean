#!/usr/bin/env python3
"""Build the static documentation site of this repository.

Usage: python3 site/build.py OUTDIR --lean-pkg-pages DIR

Every page is rendered from the repository's own files (README.md, NOTICE.md) plus the
few hand-written pages in site/, and two pages generated by lean-pkg: DIR holds
verification.md and coverage.md as written by
`lean-pkg page airy1-gumbel-lean --site DIR` at the release (the verification page from
the recorded receipts, and every coverage.yaml row with its claims, inputs and notes);
they are rendered as verification.html and coverage.html without change of content.
Those files are the authority; the site repeats them and adds navigation. The output
is plain static HTML (served with .nojekyll from the gh-pages branch): no Jekyll, no
GitHub Actions build, no external script or font. Requires Python-Markdown (3.x).

The README block between the lean-pkg:page markers is not rendered from the README: the
same content (from the same data) is the generated verification page, and README links
to its sections go there.

Links: a link to a file that has a page here goes to that page; any other relative
link goes to the file on GitHub (blob/main or tree/main); README anchors go to the
page that carries that section.
"""
import html
import os
import re
import shutil
import sys

import markdown

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GH = "https://github.com/chenle02/airy1-gumbel-lean"
SITE_URL = "https://chenle02.github.io/airy1-gumbel-lean/"
PAPER_URL = "https://arxiv.org/abs/2611.23658v1"
SITE_TITLE = "Airy₁ Gumbel: Lean Companion"
TAGLINE = ("Lean 4 paper companion · Theorem 1.1 under three named inputs "
           "· Apache-2.0")
DESCRIPTION = ("Lean 4 companion to Le Chen and Fei Pu, Gumbel Fluctuations of the Maximum "
               "of the Airy_1 Process (arXiv:2611.23658v1): Theorem 1.1 verified (build and "
               "statement comparison) under three named inputs, Airy1FddPositive, "
               "GOELeftTail and CubicStrongMixing; the mesoscopic step is proved by a "
               "two-time Fredholm determinant bound instead of the paper's association "
               "route. It does not certify the whole manuscript. Apache-2.0.")

# page file -> (title, list of sources). A source is ("file", path), ("readme", [sections]),
# ("hand", path under site/) or ("gen", name in the lean-pkg pages directory).
PAGES = [
    ("index.html", "Home", [("hand", "index.md")]),
    ("getting-started.html", "Build and verify", [("readme", ["Build and verify"])]),
    ("verification.html", "Verification page (lean-pkg)", [("gen", "verification.md")]),
    ("coverage.html", "Coverage by result (lean-pkg)", [("gen", "coverage.md")]),
    ("trust.html", "Trust and axioms",
     [("hand", "coverage-note.md"), ("readme", ["Trust and axioms"])]),
    ("paper.html", "Paper, authors and citation",
     [("readme", ["Paper and references", "Authors and AI disclosure", "Built with lean-pkg"])]),
    ("notice.html", "Notice", [("file", "NOTICE.md")]),
]

MENU = [
    ("Start", [("index.html", "Home"), ("getting-started.html", "Build and verify")]),
    ("Results", [("verification.html", "Verification page (lean-pkg)"),
                 ("coverage.html", "Coverage by result (lean-pkg)"),
                 (GH + "/blob/main/Challenge.lean", "Challenge.lean (GitHub)")]),
    ("About", [("trust.html", "Trust and axioms"),
               ("paper.html", "Paper, authors and citation"),
               ("notice.html", "Notice")]),
]

# repository files that have a page on this site
FILE_PAGES = {
    "README.md": "index.html",
    "NOTICE.md": "notice.html",
}

# the sections of the lean-pkg block of README.md: they are on the generated verification page
GENERATED_SECTIONS = ("Verification at a glance", "The paper's results in Lean", "Not formalized",
                      "What the checks establish", "How this was checked", "Citation", "License",
                      "Acknowledgments")


def slug(text):
    """GitHub-style heading anchor."""
    s = re.sub(r"<[^>]+>", "", text).strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def readme_sections():
    """README.md (without the lean-pkg block) split into its level-2 sections, plus the
    introduction between the title and the first section."""
    text = open(os.path.join(REPO, "README.md"), encoding="utf-8").read()
    text = re.sub(r"(?s)<!-- lean-pkg:page:begin -->.*?<!-- lean-pkg:page:end -->", "", text)
    parts = re.split(r"(?m)^## (.+)$", text)
    head, sections = parts[0], {}
    for i in range(1, len(parts), 2):
        sections[parts[i].strip()] = "## " + parts[i] + parts[i + 1]
    intro = re.sub(r"(?m)\A\s*# .*\n", "", head).strip()
    return sections, intro


SECTIONS, INTRO = readme_sections()

# README anchor -> page carrying that section
ANCHOR_PAGE = {}
for page, _title, sources in PAGES:
    for kind, arg in sources:
        if kind == "readme":
            for name in arg:
                ANCHOR_PAGE[slug(name)] = page
ANCHOR_PAGE[slug("What is proved")] = "index.html"
ANCHOR_PAGE[slug("Comparator check of the headline")] = "getting-started.html"
for name in GENERATED_SECTIONS:
    ANCHOR_PAGE[slug(name)] = "verification.html"


def alerts(md):
    """GitHub alert blocks (> [!IMPORTANT] ...) -> a boundary box."""
    out, lines, i = [], md.splitlines(), 0
    while i < len(lines):
        m = re.match(r"^> \[!(IMPORTANT|NOTE|WARNING|CAUTION|TIP)\]\s*$", lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        i += 1
        body = []
        while i < len(lines) and lines[i].startswith(">"):
            body.append(lines[i][1:].lstrip(" ") if lines[i] != ">" else "")
            i += 1
        # GitHub starts a list right after a paragraph line; Python-Markdown needs a blank line
        fixed = []
        for line in body:
            if (re.match(r"^[-*] ", line) and fixed and fixed[-1].strip()
                    and not re.match(r"^\s*[-*] |^\s+\S", fixed[-1])):
                fixed.append("")
            fixed.append(line)
        out += ['<div class="boundary" markdown="1">', ""] + fixed + ["", "</div>"]
    return "\n".join(out)


def mark_html_blocks(md):
    """Let Markdown inside <details>/<div> blocks render (md_in_html)."""
    md = re.sub(r"<details>", '<details markdown="1">', md)
    md = re.sub(r"<div align=\"center\">", '<div markdown="1">', md)
    return md


def expand_includes(md):
    def repl(m):
        src, what = m.group(1), m.group(2).strip()
        if src == "README.md":
            if what == "intro":
                return INTRO
            if what.startswith("section:"):
                name = what.split(":", 1)[1].strip()
                if name not in SECTIONS:
                    raise SystemExit("README section missing: %s (review site/)" % name)
                return SECTIONS[name]
        else:
            return open(os.path.join(REPO, src), encoding="utf-8").read()
        raise SystemExit("unknown include: " + m.group(0))
    return re.sub(r"<!-- include (\S+)\s*([^>]*?)-->", repl, md)


def rewrite_link(target, from_path):
    """A relative link of a Markdown file at from_path (repository-relative)."""
    if re.match(r"^[a-z]+:", target) or target.startswith("//"):
        return target
    if target.startswith("#"):
        if from_path == "README.md":
            page = ANCHOR_PAGE.get(target[1:])
            if page:
                return page if "#" in page else page + target
        return target
    path, _, frag = target.partition("#")
    if path in {p for p, _t, _s in PAGES}:
        return target
    full = os.path.normpath(os.path.join(os.path.dirname(from_path), path))
    if full in FILE_PAGES:
        return FILE_PAGES[full] + ("#" + frag if frag else "")
    kind = "tree" if os.path.isdir(os.path.join(REPO, full)) else "blob"
    if not os.path.exists(os.path.join(REPO, full)):
        raise SystemExit("link to a missing file: %s (in %s)" % (target, from_path))
    return "%s/%s/main/%s%s" % (GH, kind, full, "#" + frag if frag else "")


def rewrite_links(md, from_path):
    # inline Markdown links and images outside code; code spans are protected first
    stash = []

    def keep(m):
        stash.append(m.group(0))
        return "\x00%d\x00" % (len(stash) - 1)
    md = re.sub(r"(?s)```.*?```", keep, md)
    md = re.sub(r"`[^`\n]*`", keep, md)
    md = re.sub(r"(\]\()([^)\s]+)(\))",
                lambda m: m.group(1) + rewrite_link(m.group(2), from_path) + m.group(3), md)
    # href="..." in raw HTML (for example inside a <summary>)
    md = re.sub(r'(href=")([^"]+)(")',
                lambda m: m.group(1) + rewrite_link(m.group(2), from_path) + m.group(3), md)
    return re.sub(r"\x00(\d+)\x00", lambda m: stash[int(m.group(1))], md)


def render(md):
    conv = markdown.Markdown(extensions=["tables", "fenced_code", "md_in_html", "toc", "sane_lists"],
                             extension_configs={"toc": {"slugify": lambda v, sep: slug(v)}})
    # lean-pkg escapes `~` as `\~`; Python-Markdown does not treat that as an escape by
    # default and would print the backslash.
    if "~" not in conv.ESCAPED_CHARS:
        conv.ESCAPED_CHARS.append("~")
    return conv.convert(md)


GEN_PAGES = {"verification.md": "verification.html", "coverage.md": "coverage.html"}
GEN_DIR = None


def gen_markdown(name):
    """A lean-pkg generated page: its links between the two pages go to their HTML pages; a
    relative link to a repository file goes to GitHub like any other."""
    md = open(os.path.join(GEN_DIR, name), encoding="utf-8").read()
    for a, b in GEN_PAGES.items():
        md = re.sub(r"\]\(%s(#[^)]*)?\)" % re.escape(a), lambda m: "](" + b + (m.group(1) or "") + ")", md)
    return rewrite_links(md, "README.md")


def page_markdown(sources):
    chunks = []
    for kind, arg in sources:
        if kind == "gen":
            if arg == "verification.md":     # a reading note before the generated page (not inside it)
                note = open(os.path.join(REPO, "site", "verification-note.md"), encoding="utf-8").read()
                chunks.append(rewrite_links(alerts(mark_html_blocks(note)), "README.md"))
            chunks.append(gen_markdown(arg))
            continue
        if kind == "hand":
            md = open(os.path.join(REPO, "site", arg), encoding="utf-8").read()
            md = expand_includes(md)
            md = rewrite_links(alerts(mark_html_blocks(md)), "README.md")
        elif kind == "readme":
            md = "\n\n".join(SECTIONS[name] for name in arg)
            md = rewrite_links(alerts(mark_html_blocks(md)), "README.md")
        else:
            md = open(os.path.join(REPO, arg), encoding="utf-8").read()
            md = re.sub(r"\A# .*\n", "", md)    # the page has its own title
            md = rewrite_links(alerts(mark_html_blocks(md)), arg)
        chunks.append(md)
    return "\n\n".join(chunks)


def menu_html(current):
    out = []
    for group, items in MENU:
        out.append('<p class="group">%s</p>\n<ul>' % html.escape(group))
        for href, label in items:
            cur = ' aria-current="page"' if href == current else ""
            out.append('<li><a href="%s"%s>%s</a></li>' % (href, cur, html.escape(label)))
        out.append("</ul>")
    out.append('<p class="group">Elsewhere</p>\n<ul>')
    out.append('<li><a href="%s">Source on GitHub</a></li>' % GH)
    out.append('<li><a href="%s">The paper (arXiv:2611.23658v1)</a></li>' % PAPER_URL)
    out.append('<li><a href="%s/blob/main/CITATION.cff">CITATION.cff</a></li>' % GH)
    out.append('<li><a href="llms.txt">llms.txt</a></li>')
    out.append("</ul>")
    return "\n".join(out)


FOOTER = ('airy1-gumbel-lean · Lean code by Le Chen · the paper is by Le Chen and Fei Pu '
          '(<a href="%s">arXiv:2611.23658v1</a>) · developed with '
          '<a href="https://github.com/lean-pkg/lean-pkg">lean-pkg</a> · '
          '<a href="%s/blob/main/CITATION.cff">CITATION.cff</a> · '
          '<a href="%s/blob/main/LICENSE">Apache-2.0</a>' % (PAPER_URL, GH, GH))


def main():
    global GEN_DIR
    if len(sys.argv) != 4 or sys.argv[2] != "--lean-pkg-pages":
        raise SystemExit(__doc__)
    GEN_DIR = os.path.abspath(sys.argv[3])
    for name in GEN_PAGES:
        if not os.path.isfile(os.path.join(GEN_DIR, name)):
            raise SystemExit("missing generated page: " + os.path.join(GEN_DIR, name))
    out = os.path.abspath(sys.argv[1])
    if os.path.exists(out):
        raise SystemExit("refusing to overwrite an existing directory: " + out)
    os.makedirs(out)
    layout = open(os.path.join(REPO, "site", "layout.html"), encoding="utf-8").read()
    for page, title, sources in PAGES:
        body = render(page_markdown(sources))
        if page != "index.html":
            body = "<h1>%s</h1>\n%s" % (html.escape(title), body)
        full_title = SITE_TITLE if page == "index.html" else "%s · %s" % (title, SITE_TITLE)
        doc = layout
        for key, val in (("{title}", html.escape(full_title)),
                         ("{description}", html.escape(DESCRIPTION)),
                         ("{canonical}", SITE_URL + ("" if page == "index.html" else page)),
                         ("{site_title}", html.escape(SITE_TITLE)),
                         ("{tagline}", html.escape(TAGLINE)),
                         ("{menu}", menu_html(page)),
                         ("{footer}", FOOTER)):
            doc = doc.replace(key, val)
        doc = doc.replace("{content}", body)
        with open(os.path.join(out, page), "w", encoding="utf-8") as fh:
            fh.write(doc)
    shutil.copytree(os.path.join(REPO, "site", "assets"), os.path.join(out, "assets"))
    shutil.copy(os.path.join(REPO, "site", "llms.txt"), os.path.join(out, "llms.txt"))
    open(os.path.join(out, ".nojekyll"), "w").close()
    print("built %d pages in %s" % (len(PAGES), out))


if __name__ == "__main__":
    main()
